import duckdb, sys
sys.stdout.reconfigure(encoding='utf-8')
con = duckdb.connect("data/sp_mvp.duckdb")
con.execute("SET enable_progress_bar=false")
r = con.execute("SELECT COUNT(*) FROM dim_municipio WHERE sigla_uf='SP'").fetchone()
print("SP dim_municipio:", r[0])
r2 = con.execute("SELECT COUNT(DISTINCT e.id_municipio) FROM fct_empregos e JOIN dim_municipio d ON d.id_municipio=e.id_municipio WHERE d.sigla_uf='SP'").fetchone()
print("SP fct_empregos:", r2[0])
r3 = con.execute("SELECT COUNT(DISTINCT id_municipio) FROM fct_mercado_superior WHERE sigla_uf='SP' AND ano=2024").fetchone()
print("SP fct_mercado_superior 2024:", r3[0])
r4 = con.execute("SELECT COUNT(DISTINCT e.id_municipio) FROM fct_empresas e JOIN dim_municipio d ON d.id_municipio=e.id_municipio WHERE d.sigla_uf='SP'").fetchone()
print("SP fct_empresas:", r4[0])
print()
print("--- DESCRIBE dim_municipio ---")
print(con.execute("DESCRIBE dim_municipio").df()[["column_name","column_type"]].to_string(index=False))
print()
print("--- DESCRIBE fct_empregos ---")
print(con.execute("DESCRIBE fct_empregos").df()[["column_name","column_type"]].to_string(index=False))
print()
print("--- DESCRIBE fct_mercado_superior ---")
print(con.execute("DESCRIBE fct_mercado_superior").df()[["column_name","column_type"]].to_string(index=False))
print()
print("--- DESCRIBE fct_empresas ---")
print(con.execute("DESCRIBE fct_empresas").df()[["column_name","column_type"]].to_string(index=False))
con.close()
